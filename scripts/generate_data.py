#!/usr/bin/env python3
"""Generate src/data.ts from the Clause Bank workbook (scripts/clause_bank.xlsx).

The site is the view-only, searchable version of the spreadsheet: its Clause
Bank, Read Me First, and Theme Index tabs. All text is taken verbatim.

Run:  npm run gen   (needs: pip install openpyxl)
"""
import json
import os
import re

import openpyxl

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
XLSX = os.path.join(HERE, "clause_bank.xlsx")
OUT = os.path.join(ROOT, "src", "data.ts")

PRIORITY_KEYS = ["preservation", "serviceAvailability", "patronPrivacy", "accessibility", "resourceSharing"]
PRIORITY_LABELS = {
    "preservation": "Preservation",
    "serviceAvailability": "Service Availability",
    "patronPrivacy": "Patron Privacy",
    "accessibility": "Accessibility",
    "resourceSharing": "Resource Sharing",
}
README_HEADINGS = {
    "Intro", "Notes on Organization: Rows and Columns", "Notes on Organization: Priority",
    "How You Can Use This Resource", "Working with the Risk Exposure Scorecard",
    "Color Coding", "IMPORTANT!", "About",
}


def clean(v):
    if v is None:
        return ""
    return str(v).replace("\r\n", "\n").replace("\r", "\n").strip()


def paragraphs(text):
    text = clean(text)
    if not text:
        return []
    parts = re.split(r"\n\s*\n", text)
    if len(parts) == 1:
        parts = text.split("\n")
    return [p.strip() for p in parts if p.strip()]


def watch_items(text):
    """Watch For cells are a run of sentences; show one item per sentence."""
    text = re.sub(r"\s+", " ", clean(text))
    items = re.split(r"(?:(?<=\.)|(?<=\.’)|(?<=\.'))\s+(?=[A-Z'‘“\"])", text)
    return [i.strip() for i in items if i.strip()]


def main():
    wb = openpyxl.load_workbook(XLSX, data_only=True)

    clauses, theme_order, current = [], [], None
    for row in wb["Clause Bank"].iter_rows(values_only=True):
        cells = [clean(c) for c in row] + [""] * 15
        cid = cells[0]
        if not cid or cid == "Clause ID":
            continue
        if not cells[1] and not cells[4] and not cells[5]:  # theme group header row
            current = cid
            if cid not in theme_order:
                theme_order.append(cid)
            continue
        theme = cells[2] or current
        if theme not in theme_order:
            theme_order.append(theme)
        clauses.append({
            "id": cid,
            "topic": cells[1],
            "theme": theme,
            "section": cells[3],
            "proVendor": paragraphs(row[4]),
            "proLibrary": paragraphs(row[5]),
            "fallback": paragraphs(row[6]),
            "why": clean(row[7]),
            "watchFor": watch_items(row[8]),
            "companionRef": cells[9],
            "priorities": {k: cells[10 + i] for i, k in enumerate(PRIORITY_KEYS)},
        })

    lines = [clean(r[0]) for r in wb["Read Me First"].iter_rows(values_only=True)]
    lines = [l for l in lines if l]
    title, subtitle = lines[0], lines[1]
    last_updated = next((l for l in lines if l.startswith("Last updated")), "")
    readme, cur = [], None
    for line in lines[2:]:
        if line == last_updated:
            continue
        if line in README_HEADINGS:
            cur = {"heading": line, "body": []}
            readme.append(cur)
        elif cur is not None:
            cur["body"].append(line)

    ws = wb["Theme Index"]
    ti_lines = [l for l in (clean(r[0]) for r in ws.iter_rows(min_col=1, max_col=1, values_only=True)) if l]
    ti_title, ti_intro = ti_lines[0], ti_lines[1]

    def dump(o):
        return json.dumps(o, ensure_ascii=False, indent=2)

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("""// AUTO-GENERATED by scripts/generate_data.py from scripts/clause_bank.xlsx — do not edit.
// © 2026 Library Futures / The Engelberg Center on Innovation Law & Policy. CC-BY-4.0.

export type Priority = "H" | "M" | "";
export type PriorityKey = "preservation" | "serviceAvailability" | "patronPrivacy" | "accessibility" | "resourceSharing";

export interface Clause {
  id: string;
  topic: string;
  theme: string;
  section: string;
  proVendor: string[];
  proLibrary: string[];
  fallback: string[];
  why: string;
  watchFor: string[];
  companionRef: string;
  priorities: Record<PriorityKey, Priority>;
}
export interface ReadmeSection { heading: string; body: string[] }
""")
        f.write(f"\nexport const TITLE = {json.dumps(title, ensure_ascii=False)};\n")
        f.write(f"export const SUBTITLE = {json.dumps(subtitle, ensure_ascii=False)};\n")
        f.write(f"export const LAST_UPDATED = {json.dumps(last_updated, ensure_ascii=False)};\n")
        f.write(f"export const PRIORITY_KEYS: PriorityKey[] = {dump(PRIORITY_KEYS)};\n")
        f.write(f"export const PRIORITY_LABELS: Record<PriorityKey, string> = {dump(PRIORITY_LABELS)};\n")
        f.write(f"export const THEME_ORDER: string[] = {dump(theme_order)};\n")
        f.write(f"export const THEME_INDEX_TITLE = {json.dumps(ti_title, ensure_ascii=False)};\n")
        f.write(f"export const THEME_INDEX_INTRO = {json.dumps(ti_intro, ensure_ascii=False)};\n")
        f.write(f"export const CLAUSES: Clause[] = {dump(clauses)};\n")
        f.write(f"export const README_SECTIONS: ReadmeSection[] = {dump(readme)};\n")

    print(f"clauses: {len(clauses)}  themes: {len(theme_order)}  readme sections: {len(readme)}  {last_updated}")


if __name__ == "__main__":
    main()
